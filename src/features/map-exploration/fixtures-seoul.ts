/**
 * north/south는 한강 방향으로 넘지 않도록 중심 기준 북/남쪽 최대 오프셋(lat, 기본 0.005)이다.
 * scale은 이웃 권역 polygon이 겹치지 않도록 줄인 크기 배율이다.
 */
